void Canvas::fill(int x, int y, int w, int h, uint32_t c) {
  const int x0 = std::max(x, 0), y0 = std::max(y, 0), x1 = std::min(x + w, kW), y1 = std::min(y + h, kH);
  for (int yy = y0; yy < y1; yy++)
    std::fill(px.begin() + yy * kW + x0, px.begin() + yy * kW + std::max(x1, x0), c);
}

int Canvas::text(int x, int y, const std::string &s, uint32_t c) {
  for (const char ch : s) {
    const unsigned char u = static_cast<unsigned char>(ch);
    const uint8_t *g = kFont[u >= 32 && u <= 126 ? u - 32 : '?' - 32];
    for (int col = 0; col < 5; col++)
      for (int row = 0; row < 8; row++) // (row 7: descenders)
        if (g[col] >> row & 1)
          put(x + col, y + row, c);
    x += kCharW;
  }
  return x;
}

